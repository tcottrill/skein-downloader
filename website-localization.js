  const storageKey = "skein-site-language";
  const getSavedLanguage = () => {
    try {
      const saved = localStorage.getItem(storageKey);
      return saved === "system" || languages.some(language => language.code === saved) ? saved : null;
    } catch { return null; }
  };
  const browserLanguage = () => {
    const preferences = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
    for (const preference of preferences) {
      const tag = preference.toLowerCase().replaceAll("_", "-");
      if (/^zh(?:-|$)/.test(tag)) {
        if (/(?:^|-)hant(?:-|$)/.test(tag)) return "zh_TW";
        if (/(?:^|-)hans(?:-|$)/.test(tag)) return "zh_CN";
        if (/(?:^|-)tw(?:-|$)|(?:^|-)hk(?:-|$)|(?:^|-)mo(?:-|$)/.test(tag)) return "zh_TW";
        return "zh_CN";
      }
      const base = tag.split("-")[0];
      if (messages[base]) return base;
    }
    return "en";
  };
  const icon = country => country === "globe"
    ? '<span class="flag" aria-hidden="true">🌐</span>'
    : `<svg class="flag" aria-hidden="true" viewBox="0 0 24 24">${flagArtwork[country]}</svg>`;
  const picker = document.getElementById("languagePicker");
  const menu = document.getElementById("languageMenu");
  const currentLanguage = document.getElementById("currentLanguage");
  const getCurrentFlag = () => document.getElementById("currentFlag");
  if (!picker || !menu || !currentLanguage || !getCurrentFlag()) return;

  let selected = getSavedLanguage();
  if (!selected) selected = "system";
  const resolved = () => selected === "system" ? browserLanguage() : selected;
  const renderMenu = activeCode => {
    const labels = messages[activeCode];
    const allChoices = [{ code: "system", name: labels.sameAsSystem, flag: "globe" }, ...languages];
    menu.innerHTML = allChoices.map(choice => `<button type="button" data-language="${choice.code}"${choice.code === selected ? ' aria-current="true"' : ""} class="${choice.code === "system" ? "system-choice" : ""}">${icon(choice.flag)}<span>${choice.name}</span></button>`).join("");
  };
  const apply = () => {
    const code = resolved();
    const labels = messages[code] || messages.en;
    document.documentElement.lang = code.replace("_", "-");
    document.title = labels.pageTitle;
    document.querySelector('meta[name="description"]').content = labels.metaDescription;
    document.querySelectorAll("[data-i18n]").forEach(element => {
      const value = labels[element.dataset.i18n];
      if (value !== undefined) element.innerHTML = value;
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(element => {
      element.dataset.i18nAttr.split(",").forEach(pair => {
        const [attribute, key] = pair.split(":");
        if (labels[key] !== undefined) element.setAttribute(attribute, labels[key]);
      });
    });
    currentLanguage.textContent = languages.find(language => language.code === code).name;
    getCurrentFlag().outerHTML = icon(languages.find(language => language.code === code).flag).replace("class=\"flag\"", 'class="flag" id="currentFlag"');
    renderMenu(code);
  };
  apply();
  menu.addEventListener("click", event => {
    const button = event.target.closest("button[data-language]");
    if (!button) return;
    selected = button.dataset.language;
    try { localStorage.setItem(storageKey, selected); } catch { /* Language remains active for this page view. */ }
    apply();
    picker.open = false;
    picker.querySelector("summary").focus();
  });
  document.addEventListener("click", event => {
    if (!picker.contains(event.target)) picker.open = false;
  });
  document.addEventListener("keydown", event => {
    if (event.key === "Escape" && picker.open) {
      picker.open = false;
      picker.querySelector("summary").focus();
    }
  });
